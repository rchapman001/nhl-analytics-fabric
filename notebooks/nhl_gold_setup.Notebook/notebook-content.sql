-- ============================================================
-- VERIFICATION - GOLD WAREHOUSE TABLES
-- ============================================================

SELECT
    'nhl_gold_warehouse' AS warehouse_name,
    s.name AS schema_name,
    t.name AS table_name
FROM nhl_gold_warehouse.sys.tables t
INNER JOIN nhl_gold_warehouse.sys.schemas s
    ON t.schema_id = s.schema_id
WHERE s.name = 'dbo'
  AND t.name IN (
      'dim_team',
      'dim_player',
      'dim_date',
      'dim_game',
      'fact_rosters',
      'fact_team_standings',
      'fact_player_game_stats'
  )
ORDER BY
    warehouse_name,
    table_name;



-- ============================================================
-- COLUMN VERIFICATION
-- ============================================================

SELECT
    t.name AS table_name,
    c.column_id,
    c.name AS column_name,
    TYPE_NAME(c.user_type_id) AS data_type,
    c.max_length,
    c.is_nullable,
    c.is_identity
FROM nhl_gold_warehouse.sys.tables t
INNER JOIN nhl_gold_warehouse.sys.columns c
    ON t.object_id = c.object_id
INNER JOIN nhl_gold_warehouse.sys.schemas s
    ON t.schema_id = s.schema_id
WHERE s.name = 'dbo'
  AND t.name IN (
      'dim_team',
      'dim_player',
      'dim_date',
      'dim_game',
      'fact_rosters',
      'fact_team_standings',
      'fact_player_game_stats'
  )
ORDER BY
    t.name,
    c.column_id;

