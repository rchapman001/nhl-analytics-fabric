-- ============================================================
-- NHL ANALYTICS - GOLD WAREHOUSE TABLE SETUP
-- ============================================================
--
-- Target Warehouse:
--   nhl_gold_warehouse
--
-- Source Schema:
--   PostgreSQL gold schema
--
-- Architecture:
--
--   Silver Natural Keys
--          ↓
--   Gold Natural Keys (nhl_*_id)
--          ↓
--   Gold Surrogate Keys (BIGINT IDENTITY)
--          ↓
--   Gold Fact Tables
--
-- Fabric Warehouse Requirements:
--
--   1. IDENTITY columns must use BIGINT.
--   2. Fabric Warehouse does NOT support specifying
--      IDENTITY seed or increment values.
--
--   Correct Fabric syntax:
--
--       BIGINT IDENTITY
--
--   NOT:
--
--       BIGINT IDENTITY(1,1)
--
-- ============================================================



-- ============================================================
-- DIM TEAM
-- ============================================================
--
-- team_id:
--   Gold surrogate key generated by Fabric Warehouse.
--
-- nhl_team_id:
--   NHL API natural/business key.
--
-- ============================================================

CREATE TABLE nhl_gold_warehouse.dbo.dim_team (

    -- Surrogate Key
    team_id BIGINT NOT NULL IDENTITY,

    -- NHL API Business Key
    nhl_team_id INT NOT NULL,

    -- Team Information
    place_name VARCHAR(100),
    team_name VARCHAR(100) NOT NULL,
    team_common_name VARCHAR(100),
    team_abbrev VARCHAR(10) NOT NULL,

    -- Organization
    conference_abbrev VARCHAR(10),
    conference_name VARCHAR(100),
    division_abbrev VARCHAR(10),
    division_name VARCHAR(100),

    -- Assets
    team_logo VARCHAR(1000),

    -- Audit
    created_at DATETIME2(6),
    updated_at DATETIME2(6)
);



-- ============================================================
-- DIM PLAYER
-- ============================================================
--
-- player_id:
--   Gold surrogate key generated by Fabric Warehouse.
--
-- nhl_player_id:
--   NHL API natural/business key.
--
-- draft_team_id:
--   Gold surrogate key referencing dim_team.team_id.
--
-- ============================================================

CREATE TABLE nhl_gold_warehouse.dbo.dim_player (

    -- Surrogate Key
    player_id BIGINT NOT NULL IDENTITY,

    -- NHL API Business Key
    nhl_player_id INT NOT NULL,

    -- Relationships
    draft_team_id BIGINT,

    -- Player Information
    first_name VARCHAR(100),
    last_name VARCHAR(100),
    player_slug VARCHAR(255),

    -- Current Player Information
    is_active BIT,
    position VARCHAR(50),
    shoots_catches VARCHAR(10),

    -- Physical Attributes
    height_in_inches INT,
    height_in_centimeters INT,
    weight_in_pounds INT,
    weight_in_kilograms INT,

    -- Birth Information
    birth_date DATE,
    birth_city VARCHAR(100),
    birth_country VARCHAR(100),

    -- Draft Information
    draft_year INT,
    draft_round INT,
    draft_pick_in_round INT,
    draft_overall_pick INT,

    -- Honors
    in_top_100_all_time BIT,
    in_hhof BIT,

    -- Assets
    headshot VARCHAR(1000),
    hero_image VARCHAR(1000),

    -- Audit
    created_at DATETIME2(6),
    updated_at DATETIME2(6)
);



-- ============================================================
-- DIM DATE
-- ============================================================
--
-- date_id:
--   Deterministic date key.
--
-- Example:
--   September 3, 2026 = 20260903
--
-- This is NOT an identity column.
--
-- ============================================================

CREATE TABLE nhl_gold_warehouse.dbo.dim_date (

    -- Date Key
    date_id INT NOT NULL,

    -- Date
    full_date DATE NOT NULL,

    -- Day
    day_of_month INT,
    day_name VARCHAR(20),
    day_of_week INT,

    -- Week
    week_of_year INT,

    -- Month
    month_number INT,
    month_name VARCHAR(20),

    -- Quarter
    quarter INT,

    -- Year
    year INT,

    -- Weekend Indicator
    is_weekend BIT,

    -- Audit
    created_at DATETIME2(6),
    updated_at DATETIME2(6)
);



-- ============================================================
-- DIM GAME
-- ============================================================
--
-- game_id:
--   Gold surrogate key generated by Fabric Warehouse.
--
-- nhl_game_id:
--   NHL API natural/business key.
--
-- date_id:
--   Gold date dimension key.
--
-- away_team_id / home_team_id:
--   Gold dim_team surrogate keys.
--
-- ============================================================

CREATE TABLE nhl_gold_warehouse.dbo.dim_game (

    -- Surrogate Key
    game_id BIGINT NOT NULL IDENTITY,

    -- NHL API Business Key
    nhl_game_id INT NOT NULL,

    -- Date Relationship
    date_id INT NOT NULL,

    -- Game Context
    season_id INT NOT NULL,
    game_type_id INT NOT NULL,
    game_date DATE,
    start_time_utc DATETIME2(6),

    -- Team Relationships
    away_team_id BIGINT NOT NULL,
    home_team_id BIGINT NOT NULL,

    -- Game Results
    away_team_score INT,
    home_team_score INT,
    away_shots_on_goal INT,
    home_shots_on_goal INT,

    -- Venue
    venue VARCHAR(255),
    venue_time_zone VARCHAR(100),

    -- Audit
    created_at DATETIME2(6),
    updated_at DATETIME2(6)
);



